# Regenerates sw.js with the list of every file the app needs offline. Run from the repo root: python3 tools/build_sw.py
# The OCR engine (assets/vendor) is not pre-cached (it is large); it is cached the first time the Scanner opens online.
import os, hashlib
files = []
for root, _, names in os.walk('.'):
    if root.startswith(('./.git', './docs', './tools', './assets/vendor')): continue
    for n in names:
        p = os.path.join(root, n)[2:]
        if p.endswith(('.html', '.css', '.js', '.woff2', '.svg', '.png', '.jpg', '.webmanifest')) and p not in ('sw.js',):
            files.append(p)
files.sort()
h = hashlib.sha1(''.join(open(f, 'rb').read().hex()[:2000] + f for f in files).encode()).hexdigest()[:10]
open('sw.js', 'w').write(f'''/* PunctuAction service worker — caches every file so the app works with no internet. Auto-generated by tools/build_sw.py */
const CACHE = "punctuaction-{h}";
const FILES = {files!r};
self.addEventListener("install", (e) => {{ e.waitUntil(caches.open(CACHE).then((c) => c.addAll(["./", ...FILES])).then(() => self.skipWaiting())); }});
self.addEventListener("activate", (e) => {{ e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); }});
self.addEventListener("fetch", (e) => {{
  if (e.request.method !== "GET") return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => hit || fetch(e.request).then((res) => {{
    if (res.ok && new URL(e.request.url).origin === location.origin) {{ const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }}
    return res;
  }}).catch(() => caches.match("index.html"))));
}});
''')
print(len(files), 'files cached', h)
